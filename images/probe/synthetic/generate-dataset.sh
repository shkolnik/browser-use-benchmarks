#!/usr/bin/env bash
# Generate incompressible probe chunks into the datasets cache, plus a
# generated Dockerfile with one COPY per chunk (layer-per-chunk is the
# knob this probe measures).
# Usage: generate-dataset.sh <datasets-dir> <num-chunks> <chunk-gb>
set -euo pipefail
dsdir=$1 n=$2 gb=$3
mkdir -p "$dsdir"
for i in $(seq -w 1 "$n"); do
  f="$dsdir/probe-chunk-$i.bin"
  if [ -s "$f" ]; then echo "exists: $f"; continue; fi
  echo "generating $f (${gb}G random)"
  head -c "${gb}G" /dev/urandom > "$f.part" && mv "$f.part" "$f"
done

gen="$(dirname "$0")/Dockerfile.generated"
{
  echo "# syntax=docker/dockerfile:1"
  echo "# GENERATED by generate-dataset.sh — one COPY per chunk (layer-per-chunk on purpose)."
  echo "FROM busybox"
  for i in $(seq -w 1 "$n"); do
    echo "COPY --from=datasets probe-chunk-$i.bin /data/"
  done
  echo "CMD ls -l /data"
} > "$gen"
echo "wrote $gen ($n COPY lines)"
